#!/usr/bin/env python3
"""Regenerate research/structure-sheets-register.md from data/structure-sheets.json.

The register is a transcription record, not a second opinion: every cell here comes
from data/structure-sheets.json (the verified reading of each official PDF) or from
data/master.json (the schedule rows that cite that sheet). Regenerate it after any
change so the document can never drift from the data the site is built from.

Run: python3 scripts/build_sheet_register.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "research", "structure-sheets-register.md")

sheets = json.load(open(os.path.join(ROOT, "data", "structure-sheets.json"), encoding="utf-8"))
master = json.load(open(os.path.join(ROOT, "data", "master.json"), encoding="utf-8"))

def money(v):
    return "—" if v is None else "${:,}".format(int(v))


SHEET_RE = re.compile(r"structure_(\d+)\.pdf")


def rows_for(sheet):
    """Rows are matched on the sheet PDF they cite, not on an event-number guess."""
    out = [e for e in master["events"] if SHEET_RE.search(str(e.get("struct_url") or ""))
           and int(SHEET_RE.search(str(e.get("struct_url"))).group(1)) == sheet["sheet"]]
    out.sort(key=lambda e: (str(e.get("date")), str(e.get("start"))))
    return out


def late_reg_cell(sheet):
    lr = sheet.get("late_reg") or ""
    if not sheet.get("reg_close"):
        return lr + " (no clock time printed)"
    return lr


lines = []
A = lines.append

A("# Venetian DeepStack Extravaganza IV — structure-sheet register")
A("")
A("Generated by `scripts/build_sheet_register.py` from `data/structure-sheets.json`, which is the")
A("transcription of every official structure PDF. Do not edit this file by hand; edit the JSON and")
A("regenerate, so the register and the site can never disagree.")
A("")
A("Coverage: **%d of %d sheets** read in full on %s." % (
    len(sheets["sheets"]), 37, sheets.get("as_of", "")))
A("")
A("Method: %s" % sheets.get("method", ""))
A("")
A("## What the sheets do and do not say about entries")
A("")
n_silent = sum(1 for s in sheets["sheets"] if s.get("silent_on_reentry"))
n_flight = sum(1 for s in sheets["sheets"] if s.get("has_flight_note"))
A("| Measure | Count |")
A("|---|---|")
A("| Sheets read in full | %d |" % len(sheets["sheets"]))
A("| Sheets that print a standalone re-entry / rebuy / add-on clause | 0 |")
A("| Sheets that print the Day-2 bagging rule (multi-flight events) | %d |" % n_flight)
A("| Sheets that print nothing about entries at all | %d |" % (len(sheets["sheets"]) - n_flight))
A("| Sheets that print an explicit one-entry-only rule | 0 |")
A("")
A("**The distinction that matters:** a structure sheet that never mentions re-entry is not")
A("evidence that re-entry is forbidden. Silence is not a prohibition, and this register does not")
A("treat it as one. Venetian one-day rows are therefore labelled *sheet silent on re-entry*, kept in")
A("their own list apart from the spend-more (re-entry / add-on) events, and flagged as needing a")
A("written answer from the poker room before any entry decision depends on them. The counter-example")
A("is Wynn: its WPT structures PDF states re-entry in writing (the $600 event allows unlimited")
A("re-entry per flight until the start of level 9), so Wynn events are classified as spend-more on")
A("the strength of a printed rule, not of silence.")
A("")
A("## Sheet-by-sheet transcription")
A("")
A("| Sheet | Official PDF | Read | Title (as printed) | Event no. | Scheduled rows (date · start) | Chips | Level | Late registration | Guarantee | Fee + pool | Entry rule on the sheet |")
A("|---|---|---|---|---|---|---|---|---|---|---|---|")
for s in sheets["sheets"]:
    rs = rows_for(s)
    sched = ", ".join("%s %s" % (str(e.get("date"))[5:], e.get("start")) for e in rs) or "—"
    gtd = money(s.get("gtd"))
    if gtd == "—":
        gtd = "none printed"
    feepool = ("%s + %s = %s" % (money(s.get("fee")), money(s.get("pool")),
                                 money((s.get("fee") or 0) + (s.get("pool") or 0)))
                if s.get("fee") is not None else "—")
    if s.get("has_flight_note"):
        rule = ("Day-2 bagging rule only: whoever bags Day 2 chips may not play another flight, "
                "so a player who does not bag may take another flight")
    else:
        rule = "Nothing about entries — **silent**, which is not a prohibition"
    A("| %d | [PDF](%s) | %s | %s | %s | %s | %s | %s min | %s | %s | %s | %s |" % (
        s["sheet"], s["url"], s.get("retrieved", ""), s.get("title", ""),
        ", ".join(str(n) for n in s["events"]) or "—", sched,
        "{:,}".format(s["chips"]) if s.get("chips") else "—",
        s.get("level_min") or "—", late_reg_cell(s), gtd, feepool, rule))
A("")
A("## Consistency checks run on this register")
A("")
A("* `scripts/audit.py` re-derives, for every Venetian row on the site: the sheet it cites exists in")
A("  this registry, the sheet covers that event number, the house fee matches, the chips match, the")
A("  printed late-registration wording matches, the clock close of registration matches the printed")
A("  time, and the guarantee does not contradict the sheet.")
A("* `scripts/check_links.py` confirms every PDF link here resolves to an official Venetian host.")
A("* Event numbers and dates are the schedule page's, not the sheets' — the sheets print one")
A("  structure shared by several numbered events, so a mismatch would mean the schedule page and the")
A("  PDF disagree. None was found.")
A("")
A("## Notes carried over from the schedule")
A("")
A("* Sheet 25 (turbo milestone satellite) prints \"6 levels\" with **no clock time** for the close of")
A("  registration, so its three rows carry a blank close time rather than an invented one.")
A("* Several sheets cover many one-day events with different guarantees (sheet 7: $30,000 / $40,000;")
A("  sheet 11: $30,000 / $40,000 / $50,000). The guarantee is taken from the event's own schedule row")
A("  where the sheet prints more than one figure.")
A("* Sheet 8 carries a priced subsequent buy-in clause ($200), which is a spend advantage. Those two")
A("  events (18, 58) are labelled *entry limit ambiguous*, not single-entry.")
A("* Sheets 31 and 32 describe LIPS events with eligibility conditions (female, or female/male team)")
A("  and add a flat LIPS fee on top of the house fee; the fee split here is the sheet's own.")

open(OUT, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote %s (%d sheets)" % (os.path.relpath(OUT, ROOT), len(sheets["sheets"])))
